/** The little highlight on the right lens. */
const GLINT = new Set(["42,35", "43,35", "44,34", "45,33"]);

export type Cell = { r: number; c: number; glint: boolean };

export const LOGO_CELLS: Cell[] = LOGO_ROWS.flatMap((row, r) =>
  Array.from(row).flatMap((v, c) => (v === "1" ? [{ r, c, glint: GLINT.has(`${r},${c}`) }] : [])),
);

/** Horizontal runs, handy for compact SVG output. */
export const LOGO_RUNS: { r: number; c: number; len: number }[] = LOGO_ROWS.flatMap((row, r) => {
  const runs: { r: number; c: number; len: number }[] = [];
  let c = 0;
  while (c < row.length) {
    if (row[c] === "1") {
      const start = c;
      while (c < row.length && row[c] === "1") c++;
      runs.push({ r, c: start, len: c - start });
    } else c++;
  }
  return runs;
});
