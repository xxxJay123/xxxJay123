export type Lang = "en" | "zh";
const dicts: Record<Lang, Record<Key, string>> = { en, zh };

type Ctx = { lang: Lang; t: (k: Key) => string; toggle: () => void };
const LangContext = createContext<Ctx | null>(null);

function initialLang(): Lang {
  try {
    const saved = localStorage.getItem("lang");
    if (saved === "en" || saved === "zh") return saved;
  } catch { /* storage blocked */ }
  return "en";
}

export function LangProvider({ children }: { children: ReactNode }) {
  const [lang, setLang] = useState<Lang>(initialLang);

  useEffect(() => {
    document.documentElement.lang = lang === "zh" ? "zh-Hant" : "en";
    try { localStorage.setItem("lang", lang); } catch { /* storage blocked */ }
  }, [lang]);

  const t = useCallback((k: Key) => dicts[lang][k], [lang]);
  const toggle = useCallback(() => setLang(l => (l === "en" ? "zh" : "en")), []);
  const value = useMemo(() => ({ lang, t, toggle }), [lang, t, toggle]);
  return <LangContext.Provider value={value}>{children}</LangContext.Provider>;
}

export function useLang() {
  const ctx = useContext(LangContext);
  if (!ctx) throw new Error("useLang must be used inside LangProvider");
  return ctx;
}
